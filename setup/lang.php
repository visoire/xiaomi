/**
 * Translate a key for the active language, falling back to English then the key.
 */
function t(string $key): string
{
    global $TOOLS_T, $lang;
    return $TOOLS_T[$lang][$key] ?? $TOOLS_T['en'][$key] ?? $key;
}

/**
 * Escape helper.
 */
function te(string $s): string
{
    return htmlspecialchars($s, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

/**
 * Return the active language map as a JS friendly array for inline export.
 *
 * @return array<string,string>
 */
function tjs(array $keys): array
{
    $out = [];
    foreach ($keys as $k) {
        $out[$k] = t($k);
    }
    return $out;
}
